#!/usr/bin/env node
/**
 * Writes `src/version.generated.ts` from `package.json`, for the package it is
 * RUN FROM (cwd). Used by `@civitai/blocks-react` and `@civitai/sdk`, whose
 * transports report the constant to the host as `sdkVersion` in `BLOCK_READY`.
 *
 * Each package's `build` runs this first and the root `release:version` runs
 * each package's `generate` after `changeset version`; the committed file is
 * checked against package.json by `scripts/check-generated-version.mjs`, which
 * parses the one `export const VERSION = "…";` line this emits.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const pkgRoot = process.cwd();
const { name, version } = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8'));

writeFileSync(
  join(pkgRoot, 'src', 'version.generated.ts'),
  `/* AUTOGENERATED from package.json by scripts/gen-version.mjs. DO NOT EDIT. */\n\n` +
    `/** This package's version, reported to the host as \`sdkVersion\` in \`BLOCK_READY\`. */\n` +
    `export const VERSION = ${JSON.stringify(version)};\n`,
);

console.log(`[gen-version] ${name}: wrote src/version.generated.ts (${version})`);
