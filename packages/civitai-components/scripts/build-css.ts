/**
 * Build writer for @civitai/components. `src/components.css` is the single
 * source of truth. This:
 *   - copies it to `dist/components.css` (the `<link>`-able artifact),
 *   - copies it to the package-root `styles.css` so a LITERAL CDN path
 *     `cdn.jsdelivr.net/npm/@civitai/components/styles.css` resolves to a real
 *     file (jsDelivr ignores package.json `exports`, so the `./styles.css`
 *     export alias alone 404s there; a real root file added to `files` fixes
 *     every CDN uniformly while the alias keeps bundler imports working), and
 *   - generates `src/styles.generated.ts` embedding the same CSS as a string
 *     (the JS-injectable form), compiled by tsc into dist.
 * A generation-parity test asserts the two never diverge.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, '..');
const srcCss = join(pkgRoot, 'src', 'components.css');
const distDir = join(pkgRoot, 'dist');

const css = readFileSync(srcCss, 'utf8');

mkdirSync(distDir, { recursive: true });
copyFileSync(srcCss, join(distDir, 'components.css'));
// Package-root copy so a literal CDN path `@civitai/components/styles.css`
// resolves on jsDelivr (which ignores `exports`). Byte-identical to the source.
copyFileSync(srcCss, join(pkgRoot, 'styles.css'));

const banner =
  '/* AUTOGENERATED from src/components.css by scripts/build-css.ts. DO NOT EDIT.\n' +
  '   Guarded by the generation-parity test. */';
writeFileSync(
  join(pkgRoot, 'src', 'styles.generated.ts'),
  `${banner}\n\n/** The @civitai/components stylesheet (identical to dist/components.css). */\nexport const componentsCss = ${JSON.stringify(css)};\n`
);

console.log('[build-css] wrote dist/components.css + styles.css + src/styles.generated.ts');
