import { readFileSync, writeFileSync } from 'node:fs';

// The transport's reply ledger, generated from the committed snapshot of the
// host's inventory so it covers EVERY request the host answers rather than the
// handful someone remembered to type. Refresh the snapshot with
// `npm run snapshot:host`, then run this; `--check` fails when it is stale.

const SNAPSHOT = 'snapshots/host-messages.json';
const OUT = 'src/core/transports/host-replies.generated.ts';

const host = JSON.parse(readFileSync(SNAPSHOT, 'utf8'));
const entries = Object.entries(host.messages).sort(([a], [b]) => a.localeCompare(b));
const requests = entries.filter(([, m]) => m.request);
const notifications = entries.filter(([, m]) => !m.request).map(([type]) => type);

// A snapshot that parsed empty would generate a transport that refuses everything.
if (requests.length === 0) {
  console.error(`${SNAPSHOT} has no request messages — the snapshot changed shape.`);
  process.exit(1);
}
for (const [type, m] of requests) {
  if (!m.reply || !m.framing || m.replyKeys === undefined) {
    console.error(`${type} lacks reply/framing/replyKeys in ${SNAPSHOT} — re-run \`npm run snapshot:host\`.`);
    process.exit(1);
  }
}

// One JSON value per line, so check-host-parity.mjs can read the table back
// without a TypeScript parser.
const rows = requests.map(
  ([type, m]) =>
    `  ${JSON.stringify(type)}: ${JSON.stringify({ reply: m.reply, framing: m.framing, keys: m.replyKeys })}`,
);
const text =
  `// Generated by scripts/gen-host-replies.mjs from ${SNAPSHOT}\n` +
  `// (civitai/civitai ${host.capturedFrom}, ${host.capturedAt}). Do not edit.\n\n` +
  `export interface HostReply {\n` +
  `  /** The message type the host answers with. */\n` +
  `  readonly reply: string;\n` +
  `  /** \`legacy\`: fields straight in the payload, failure as a string. */\n` +
  `  readonly framing: 'envelope' | 'legacy';\n` +
  `  /** The keys a success carries besides \`requestId\`; \`null\` where the host's literal could not be read. */\n` +
  `  readonly keys: readonly string[] | null;\n` +
  `}\n\n` +
  `/** Every request the host answers. A type absent here is one it never answers. */\n` +
  `export const HOST_REPLIES: Readonly<Record<string, HostReply>> = {\n${rows.join(',\n')},\n};\n\n` +
  `/** The host's fire-and-forget messages: it handles them and never replies. */\n` +
  `export const HOST_NOTIFICATIONS: ReadonlySet<string> = new Set([\n` +
  `${notifications.map((type) => `  ${JSON.stringify(type)},`).join('\n')}\n]);\n`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(OUT, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (committed !== text) {
    console.error(`${OUT} is stale against ${SNAPSHOT}. Run \`npm run gen:host-replies\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${requests.length} requests, ${notifications.length} notifications).`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT} (${requests.length} requests, ${notifications.length} notifications).`);
}
