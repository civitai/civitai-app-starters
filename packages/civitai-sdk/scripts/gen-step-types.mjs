import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

// The client flattens the spec's `$type` discriminator to one base type, so the
// unions are rebuilt here from the subtypes it does export.

const OUT = 'src/orchestration/steps.generated.ts';
const SOURCE = '@civitai/orchestration-client/dist/generated/types.gen.js';

const require = createRequire(import.meta.url);
const declarations = readFileSync(
  require.resolve('@civitai/orchestration-client/dist/generated/types.gen.d.ts'),
  'utf8',
);

const names = (pattern) => [...declarations.matchAll(pattern)].map((m) => m[1]).sort();
const templates = names(/^export type (\w+StepTemplate) = Omit<WorkflowStepTemplate, '\$type'>/gm);
const steps = names(/^export type (\w+Step) = Omit<WorkflowStep, '\$type'>/gm);

// A pattern that silently matches nothing would generate an empty union.
if (templates.length === 0 || steps.length === 0) {
  console.error('no typed step templates or steps found — the client changed shape.');
  process.exit(1);
}

const union = (items) => items.map((item) => `\n  | ${item}`).join('');
const text =
  `// Generated by scripts/gen-step-types.mjs from ${SOURCE}. Do not edit.\n\n` +
  `import type {\n${[...templates, ...steps].map((n) => `  ${n},`).join('\n')}\n} from '${SOURCE}';\n\n` +
  `/** Any step a workflow can be submitted with, discriminated by \`$type\`. */\n` +
  `export type StepTemplate =${union(templates)};\n\n` +
  `/** Any step a workflow reports back, discriminated by \`$type\`. */\n` +
  `export type Step =${union(steps)};\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== text) {
    console.error(`${OUT} is stale. Run \`npm run gen:steps\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${templates.length} templates, ${steps.length} steps).`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT} (${templates.length} templates, ${steps.length} steps).`);
}
