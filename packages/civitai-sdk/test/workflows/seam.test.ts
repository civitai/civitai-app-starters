import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import type {
  AppClient,
  BlockWorkflowSnapshot,
  KnownBlockWorkflowErrorCode,
  WithWorkflowStepRefs,
  WorkflowBody,
  WorkflowBodyWorkflow,
  WorkflowBodyWorkflowStep,
  WorkflowStepRef,
} from '../../src/index.js';

const read = (path: string) => readFileSync(fileURLToPath(new URL(path, import.meta.url)), 'utf8');

/**
 * What these pin is a RELATIONSHIP between files, which no unit test of the
 * client can see: the routes sit inside the block token's own namespace, the
 * contract types are a generated copy that nobody hand-edits, and every type in
 * that copy is nameable from the package root.
 */
describe('the workflows client stays inside the block token namespace', () => {
  it('names its base path textually, under `blocks/`', () => {
    // `explainApiRefusal` in `src/app/index.ts` exempts `blocks/*` from the
    // `auth: "oauth"` advice. That exemption covers this client only while its
    // base path stays under that prefix.
    expect(read('../../src/workflows/index.ts')).toContain("const BASE = 'blocks/workflows'");
    expect(read('../../src/app/index.ts')).toContain('const BLOCK_NAMESPACE = /^\\/*blocks\\//');
  });

  it('is built on the site transport, not the orchestrator one', () => {
    const app = read('../../src/app/index.ts');

    expect(app).toContain('workflows: createWorkflowsClient(siteHttp)');
    expect(app.match(/createWorkflowsClient\(/g)).toHaveLength(1);
  });

  it('re-spells no host rule: no idempotency-key pattern lives in this package', () => {
    const source = read('../../src/workflows/index.ts');

    // The host owns the key format. A second copy here is the thing that drifts.
    expect(source).not.toMatch(/A-Za-z0-9/);
    expect(source).not.toMatch(/\{1,\s*64\}/);
  });
});

describe('the contract types are a generated copy, all of it public', () => {
  const generated = read('../../src/workflows/types.generated.ts');
  const names = [...generated.matchAll(/^export (?:type|interface) ([A-Za-z_$][\w$]*)/gm)].map(
    (m) => m[1]!,
  );

  it('carries the generator banner, so it is never edited by hand', () => {
    expect(generated.startsWith('// Generated by scripts/gen-workflow-types.mjs')).toBe(true);
    expect(generated).toContain('packages/civitai-app-sdk/src/blocks/types.ts');
  });

  it('holds the types a multi-step body and its replies are written with', () => {
    // A floor, so a regex that matched nothing cannot pass the ledger below.
    expect(names.length).toBeGreaterThanOrEqual(30);
    for (const required of [
      'WorkflowBody',
      'WorkflowBodyWorkflow',
      'WorkflowBodyWorkflowStep',
      'WorkflowStepRef',
      'WithWorkflowStepRefs',
      'BlockWorkflowSnapshot',
      'KnownBlockWorkflowErrorCode',
      'AppWorkflow',
    ]) {
      expect(names).toContain(required);
    }
  });

  it('🔴 every generated type is exported from the package root, and no other is claimed', () => {
    const index = read('../../src/index.ts');
    const block = index.match(/export type \{([^}]*)\} from '\.\/workflows\/types\.generated\.js';/);

    expect(block).not.toBeNull();
    const exported = block![1]!
      .split(',')
      .map((name) => name.trim())
      .filter(Boolean);

    // Set equality in both directions: a type the copy gains must become
    // public, and a name the root lists must exist in the copy.
    expect([...exported].sort()).toEqual([...names].sort());
  });
});

/**
 * The compile-time half: a two-step body written against the package root
 * alone. `tsc -p tsconfig.test.json` is what fails if one of these stops
 * resolving; the runtime assertion only keeps the values from being unused.
 */
describe('a multi-step body is writable from `@civitai/sdk` alone', () => {
  it('types the body, a step reference and the reply', () => {
    const ref: WorkflowStepRef = { $ref: 'draw', path: 'output.images[0].url' };
    const input: WithWorkflowStepRefs<{ image: string; format?: 'png' | 'webp' }> = {
      image: ref,
      format: 'png',
    };
    const second: WorkflowBodyWorkflowStep = { name: 'cutout', $type: 'imageBackgroundRemoval', input };
    const workflow: WorkflowBodyWorkflow = {
      kind: 'workflow',
      steps: [{ name: 'draw', $type: 'imageGen', input: { prompt: 'a lighthouse' } }, second],
    };
    const body: WorkflowBody = workflow;
    const code: KnownBlockWorkflowErrorCode = 'workflow_ref_invalid';
    const reply: BlockWorkflowSnapshot = { workflowId: 'failed', status: 'failed', errorCode: code };

    expect(reply.errorCode).toBe('workflow_ref_invalid');
    expect(body.kind).toBe('workflow');

    type Estimate = AppClient['workflows']['estimate'];
    const accepts: Parameters<Estimate>[0] = body;
    expect(accepts).toBe(workflow);
  });
});
